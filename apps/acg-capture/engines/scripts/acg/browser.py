"""ego-browser 抓取层：微博时间线、小红书主页卡片、任意页面快照。

为什么单独一层：微博 / 小红书对 urllib 是登录墙（返回 visitor 壳、404），
只有带登录态的 ego-browser 才拿得到正文。因此「抓」由这一层负责，
验收层改成读本地快照（见 feeds.py 的 snapshot 索引）。

约束：
- ego-browser 不继承父进程 env，所以每次生成一个包装 mjs，在里面 setenv 再 import 目标脚本。
- 抓不到不抛异常，返回 (ok=False, error)，由调用方决定是跳过渠道还是整轮失败。
"""

from __future__ import annotations

import json
import shutil
import subprocess
import threading
import uuid
from pathlib import Path

WORKFLOW = Path(__file__).resolve().parents[2]
TIMELINE_MJS = WORKFLOW / "scripts" / "weibo_timeline.mjs"
XHS_MJS = WORKFLOW / "scripts" / "xhs_notes.mjs"

EGO = shutil.which("ego-browser")

# ego-browser 同一个 profile 不能并发：两个 nodejs 会话会互相踩，stdout 串成别人的结果。
# 所以抓取串行（单渠道 3~6s，13 个渠道也就一分钟）。
_LOCK = threading.Lock()


class BrowserError(RuntimeError):
    """ego-browser 不可用或抓取脚本报错。"""


def available() -> bool:
    return bool(EGO) and TIMELINE_MJS.exists()


def _tail(text: str, limit: int = 300) -> str:
    lines = [line for line in (text or "").strip().splitlines() if line.strip()]
    return lines[-1][:limit] if lines else ""


def _run_wrapper(body: str, workdir: Path, timeout: int) -> dict:
    """把包装脚本喂给 `ego-browser nodejs`，返回脚本最后一行 JSON。"""
    if not EGO:
        raise BrowserError("ego-browser 不在 PATH 上")
    workdir.mkdir(parents=True, exist_ok=True)
    wrapper = workdir / f"_ego_job_{uuid.uuid4().hex[:8]}.mjs"
    wrapper.write_text(body, encoding="utf-8")
    try:
        with _LOCK:
            with wrapper.open("rb") as handle:
                result = subprocess.run(
                    [EGO, "nodejs"], stdin=handle, capture_output=True, text=True, timeout=timeout
                )
    except subprocess.TimeoutExpired:
        raise BrowserError(f"ego-browser 超时（{timeout}s）")
    except OSError as error:
        raise BrowserError(f"ego-browser 启动失败：{error}")
    finally:
        wrapper.unlink(missing_ok=True)

    # ego-browser 把脚本的 console.log 也写 stderr（stdout 是空的），两边都要看
    payload = None
    for stream in (result.stderr, result.stdout):
        for line in reversed((stream or "").strip().splitlines()):
            line = line.strip()
            if line.startswith("{") and line.endswith("}"):
                try:
                    payload = json.loads(line)
                    break
                except json.JSONDecodeError:
                    continue
        if payload is not None:
            break
    if payload is None:
        raise BrowserError(f"ego-browser 退出码 {result.returncode}：{_tail(result.stderr or result.stdout)}")
    if payload.get("ok") is False:
        raise BrowserError(f"抓取脚本报错：{payload.get('error') or ''}")
    return payload


def weibo_posts(uid: str, pages: int, workdir: Path, timeout: int = 150) -> tuple[bool, list[dict], str]:
    """拉一个微博账号最近 pages 页时间线（长贴取全文），返回 (ok, posts, error)。"""
    uid = str(uid).strip()
    if not uid.isdigit():
        return False, [], "uid_invalid"
    out_path = workdir / f"weibo_{uid}.json"
    body = (
        "// generated by acg/browser.py\n"
        f"process.env.WEIBO_UID = {json.dumps(uid)};\n"
        f"process.env.WEIBO_PAGES = {json.dumps(str(int(pages)))};\n"
        f"process.env.WEIBO_OUT = {json.dumps(str(out_path))};\n"
        f"await import({json.dumps(str(TIMELINE_MJS))});\n"
    )
    try:
        _run_wrapper(body, workdir, timeout)
    except BrowserError as error:
        return False, [], str(error)
    if not out_path.exists():
        return False, [], "no_output_file"
    try:
        posts = json.loads(out_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        return False, [], f"bad_output:{error.__class__.__name__}"
    return True, [post for post in posts if isinstance(post, dict) and post.get("mid")], ""


def xhs_notes(profile_url: str, scrolls: int, workdir: Path, timeout: int = 180) -> tuple[bool, list[dict], str]:
    """抓小红书账号主页的作品卡片，返回 (ok, notes, error)。"""
    if not str(profile_url or "").startswith("http"):
        return False, [], "profile_url_invalid"
    tag = str(abs(hash(profile_url)) % 10**8)
    out_path = workdir / f"xhs_{tag}.json"
    body = (
        "// generated by acg/browser.py\n"
        f"process.env.XHS_PROFILE = {json.dumps(str(profile_url))};\n"
        f"process.env.XHS_SCROLLS = {json.dumps(str(int(scrolls)))};\n"
        f"process.env.XHS_OUT = {json.dumps(str(out_path))};\n"
        f"await import({json.dumps(str(XHS_MJS))});\n"
    )
    try:
        _run_wrapper(body, workdir, timeout)
    except BrowserError as error:
        return False, [], str(error)
    if not out_path.exists():
        return False, [], "no_output_file"
    try:
        notes = json.loads(out_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        return False, [], f"bad_output:{error.__class__.__name__}"
    return True, [note for note in notes if isinstance(note, dict) and note.get("id")], ""


def page_text(url: str, workdir: Path, timeout: int = 90) -> tuple[bool, str, str]:
    """用登录态渲染一个页面并取可见文本（公众号文章现在也是 JS 壳，urllib 拿不到正文）。"""
    if not str(url or "").startswith("http"):
        return False, "", "invalid_url"
    out_path = workdir / f"page_{uuid.uuid4().hex[:8]}.txt"
    body = (
        "// generated by acg/browser.py\n"
        "const fs = await import('node:fs/promises');\n"
        f"const URL_ = {json.dumps(str(url))};\n"
        f"const OUT = {json.dumps(str(out_path))};\n"
        "const task = await taskSpace('acg page');\n"
        "const page = task.page('p1');\n"
        "await page.goto(URL_, { timeout: 45000 });\n"
        "await new Promise((r) => setTimeout(r, 2000));\n"
        "const text = await page.evaluate(() => document.body.innerText.slice(0, 200000));\n"
        "await fs.writeFile(OUT, text, 'utf8');\n"
        "console.log(JSON.stringify({ ok: true, chars: String(text).length }));\n"
    )
    try:
        _run_wrapper(body, workdir, timeout)
    except BrowserError as error:
        return False, "", str(error)
    if not out_path.exists():
        return False, "", "no_output_file"
    return True, out_path.read_text(encoding="utf-8", errors="ignore"), ""


def page_images(url: str, workdir: Path, timeout: int = 90) -> tuple[bool, list[str], str]:
    """渲染页面并返回正文配图 URL。

    公众号图片是懒加载：`src` 是占位图，真地址在 `data-src` 里；先取 `data-src`。
    只留够大的图（>=200px），图标/表情/二维码这类小图不送去 OCR；一张大图都没有时退回全量。
    """
    if not str(url or "").startswith("http"):
        return False, [], "invalid_url"
    workdir.mkdir(parents=True, exist_ok=True)
    out_path = workdir / f"images_{uuid.uuid4().hex[:8]}.json"
    body = (
        "// generated by acg/browser.py\n"
        "const fs = await import('node:fs/promises');\n"
        f"const URL_ = {json.dumps(str(url))};\n"
        f"const OUT = {json.dumps(str(out_path))};\n"
        "const task = await taskSpace('acg images');\n"
        "const page = task.page('p1');\n"
        "await page.goto(URL_, { timeout: 45000 });\n"
        "await new Promise((r) => setTimeout(r, 2500));\n"
        "// 等正文容器出现：公众号是异步注入的，早查会只拿到页头\n"
        "await page.waitForSelector('#js_content img', { timeout: 10000 }).catch(() => null);\n"
        "// 正文图是懒加载：不滚到底 naturalWidth 一直是 0，按尺寸过滤会把图鉴全丢掉\n"
        "await page.evaluate(async () => {\n"
        "  for (let y = 0; y < document.body.scrollHeight; y += 500) {\n"
        "    window.scrollTo(0, y);\n"
        "    await new Promise((r) => setTimeout(r, 260));\n"
        "  }\n"
        "  window.scrollTo(0, document.body.scrollHeight);\n"
        "});\n"
        "await new Promise((r) => setTimeout(r, 2000));\n"
        "const imgs = await page.evaluate(() => {\n"
        "  const root = document.querySelector('#js_content') || document.body;\n"
        "  const out = [];\n"
        "  for (const el of root.querySelectorAll('img')) {\n"
        "    const src = el.getAttribute('data-src') || el.currentSrc || el.src || '';\n"
        "    if (!src.startsWith('http')) continue;\n"
        "    if (src.includes('res.wx.qq.com')) continue;  // 表情/角标图标\n"
        "    out.push({ src, w: el.naturalWidth || el.width || 0, h: el.naturalHeight || el.height || 0 });\n"
        "  }\n"
        "  return out;\n"
        "});\n"
        "// 只排除「已经加载过、明确很小」的图；还没加载的（w/h=0）照样留着\n"
        "const picked = imgs.filter((r) => !(r.w > 0 && (r.w < 200 || r.h < 200))).map((r) => r.src);\n"
        "const uniq = [...new Set(picked.map((u) => u.split('#')[0]))];\n"
        "await fs.writeFile(OUT, JSON.stringify(uniq.slice(0, 12)), 'utf8');\n"
        "console.log(JSON.stringify({ ok: true, count: picked.length }));\n"
    )
    try:
        _run_wrapper(body, workdir, timeout)
    except BrowserError as error:
        return False, [], str(error)
    if not out_path.exists():
        return False, [], "no_output_file"
    try:
        images = json.loads(out_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return False, [], "bad_output"
    return True, [str(item) for item in images if str(item).startswith("http")], ""
