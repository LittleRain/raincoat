"""社媒补充通道：微博 / 小红书。

只做「按盘名去社媒找原文」，把材料交回同一套抽取与验收（`backfill_ds._extract` + `accept.py`），
本模块不做任何业务判断。

小红书风控是本通道的第一约束，所以：
- 串行、限速（每次导航之间随机停顿），单轮盘数/笔记数都有预算；
- 一旦命中验证码、登录墙、访问频繁，立刻停这条通道，并写冷却文件，冷却期内不再发起请求；
- 只读公开内容：不点赞、不评论、不关注、不私信、不发布，也不做任何绕过验证的动作。

微博走 `m.weibo.cn` 的站内 JSON 接口（登录态 cookie 由浏览器带），比抓 s.weibo.com 页面轻得多。
"""

from __future__ import annotations

import json
import random
import time
from datetime import datetime, timedelta
from pathlib import Path

from . import browser, ocr

COOLDOWN_FILE = Path.home() / ".dsh" / "acg-capture" / "social-cooldown.json"
# 单轮预算：盘数由调用方控制，这里管单个盘的解释成本
WEIBO_LIMIT = 8
XHS_NOTES = 6
XHS_DETAILS = 2  # 只展开 2 篇笔记详情：每多开一页就多一次风控暴露
PAUSE_MIN, PAUSE_MAX = 4.0, 9.0

# 命中这些词就认定被拦：验证码 / 登录墙 / 频率限制
BLOCK_WORDS = (
    "安全验证",
    "请输入验证码",
    "验证后继续",
    "访问过于频繁",
    "操作太频繁",
    "请稍后再试",
    "登录后查看",
    "扫码登录",
    "账号异常",
)


def available() -> bool:
    return browser.available()


def _pause() -> None:
    time.sleep(random.uniform(PAUSE_MIN, PAUSE_MAX))


def blocked(page_text: str) -> str:
    """返回命中的风控词；没命中返回空串。"""
    text = str(page_text or "")[:4000]
    for word in BLOCK_WORDS:
        if word in text:
            return word
    return ""


def cooldown() -> dict:
    """冷却期内的记录；没在冷却就返回空 dict。"""
    try:
        data = json.loads(COOLDOWN_FILE.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    until = str(data.get("until") or "")
    if not until:
        return {}
    try:
        deadline = datetime.fromisoformat(until)
    except ValueError:
        return {}
    now = datetime.now(deadline.tzinfo) if deadline.tzinfo else datetime.now()
    return data if deadline > now else {}


def set_cooldown(reason: str, hours: float = 6.0) -> dict:
    until = datetime.now().astimezone() + timedelta(hours=hours)
    payload = {"until": until.isoformat(timespec="seconds"), "reason": reason, "at": datetime.now().astimezone().isoformat(timespec="seconds")}
    try:
        COOLDOWN_FILE.parent.mkdir(parents=True, exist_ok=True)
        COOLDOWN_FILE.write_text(json.dumps(payload, ensure_ascii=False), encoding="utf-8")
    except OSError:
        pass
    return payload


def keywords(pan: dict) -> list[str]:
    """一个盘在社媒上用什么词搜：盘名主体 + 赏，别名有就用别名。"""
    from .backfill_ds import clean_name

    name = clean_name(pan.get("pan") or "")
    alias = clean_name(pan.get("alias") or "")
    words: list[str] = []
    if name:
        words.append(name)
    if alias and alias != name:
        words.append(alias)
    return words[:2]


def _weibo_script(keyword: str, out_path: Path, limit: int) -> str:
    return (
        "// generated by acg/social.py\n"
        "const fs = await import('node:fs/promises');\n"
        f"const KW = {json.dumps(keyword)};\n"
        f"const OUT = {json.dumps(str(out_path))};\n"
        f"const LIMIT = {int(limit)};\n"
        "const task = await taskSpace('acg social weibo');\n"
        "const page = task.page('p1');\n"
        "await page.goto('https://m.weibo.cn/', { timeout: 45000 });\n"
        "await new Promise((r) => setTimeout(r, 1500));\n"
        "const api = 'https://m.weibo.cn/api/container/getIndex?containerid=' + encodeURIComponent('100103type=1&q=' + KW) + '&page_type=searchall';\n"
        "const payload = await page.evaluate(async (u) => {\n"
        "  const res = await fetch(u, { credentials: 'include' });\n"
        "  const text = await res.text();\n"
        "  return { status: res.status, text: text.slice(0, 400000) };\n"
        "}, api);\n"
        "let cards = [];\n"
        "try {\n"
        "  const data = JSON.parse(payload.text);\n"
        "  cards = ((data.data && data.data.cards) || [])\n"
        "    .map((c) => c.mblog)\n"
        "    .filter(Boolean)\n"
        "    .slice(0, LIMIT)\n"
        "    .map((mb) => ({\n"
        "      id: mb.mid, url: 'https://m.weibo.cn/detail/' + mb.mid,\n"
        "      created: mb.created_at || '',\n"
        "      text: String(mb.text || '').replace(/<[^>]+>/g, ''),\n"
        "      pics: (mb.pics || []).map((p) => (p.large && p.large.url) || '').filter(Boolean),\n"
        "    }));\n"
        "} catch (e) { cards = []; }\n"
        f"await fs.writeFile(OUT, JSON.stringify({{status: payload.status, cards}}, null, 1), 'utf8');\n"
        "console.log(JSON.stringify({ ok: true, count: cards.length }));\n"
    )


def search_weibo(keyword: str, workdir: Path, timeout: int = 120) -> tuple[bool, list[dict], str]:
    """微博搜一个关键词，返回 (ok, posts, error)。"""
    if not available() or not keyword:
        return False, [], "unavailable"
    workdir.mkdir(parents=True, exist_ok=True)
    out_path = workdir / f"weibo_search_{abs(hash(keyword)) % 10**8}.json"
    try:
        browser._run_wrapper(_weibo_script(keyword, out_path, WEIBO_LIMIT), workdir, timeout)
    except browser.BrowserError as error:
        return False, [], str(error)
    if not out_path.exists():
        return False, [], "no_output_file"
    try:
        data = json.loads(out_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return False, [], "bad_output"
    cards = [c for c in (data.get("cards") or []) if isinstance(c, dict)]
    joined = " ".join(str(c.get("text") or "") for c in cards)
    hit = blocked(joined)
    if hit:
        return False, [], f"blocked:{hit}"
    return True, cards, ""


def _xhs_search_script(keyword: str, out_path: Path, details: int) -> str:
    """搜索结果 → 点卡片开详情（token 由前端点击注入，直开 /explore 会 404）。"""
    return (
        "// generated by acg/social.py\n"
        "const fs = await import('node:fs/promises');\n"
        f"const KW = {json.dumps(keyword)};\n"
        f"const OUT = {json.dumps(str(out_path))};\n"
        f"const DETAILS = {int(details)};\n"
        "const task = await taskSpace('acg social xhs');\n"
        "const page = task.page('p1');\n"
        "const url = 'https://www.xiaohongshu.com/search_result?keyword=' + encodeURIComponent(KW) + '&source=web_search_result_notes';\n"
        "await page.goto(url, { timeout: 60000 });\n"
        "await new Promise((r) => setTimeout(r, 3500));\n"
        "const probe = await page.evaluate(() => ({\n"
        "  title: document.title,\n"
        "  head: (document.body ? document.body.innerText.slice(0, 800) : ''),\n"
        "  loginWall: !!document.querySelector('#login-btn') || /登录后查看搜索结果/.test((document.body && document.body.innerText) || ''),\n"
        "}));\n"
        "await page.evaluate(async () => {\n"
        "  for (let y = 0; y < 900; y += 300) { window.scrollTo(0, y); await new Promise((r) => setTimeout(r, 500)); }\n"
        "});\n"
        "const cards = await page.evaluate(() => {\n"
        "  const out = [];\n"
        "  for (const sec of document.querySelectorAll('section.note-item')) {\n"
        "    const a = sec.querySelector('a[href*=\"/explore/\"], a[href*=\"/search_result/\"]');\n"
        "    if (!a) continue;\n"
        "    const img = sec.querySelector('img');\n"
        "    out.push({ href: a.getAttribute('href') || '', text: (sec.innerText || '').replace(/\\s+/g, ' ').trim().slice(0, 400), cover: img ? (img.currentSrc || img.src || '') : '' });\n"
        "  }\n"
        "  return out.slice(0, 12);\n"
        "});\n"
        "const notes = [];\n"
        "let detailState = DETAILS > 0 ? 'pending' : 'card_only';\n"
        "for (let i = 0; i < cards.length && i < Math.max(1, DETAILS); i++) {\n"
        "  const card = cards[i];\n"
        "  const rect = await page.evaluate((idx) => {\n"
        "    const sec = document.querySelectorAll('section.note-item')[idx];\n"
        "    if (!sec) return null;\n"
        "    sec.scrollIntoView({ block: 'center' });\n"
        "    const r = sec.getBoundingClientRect();\n"
        "    return { x: Math.round(r.x + r.width / 2), y: Math.round(r.y + r.height / 2), w: Math.round(r.width) };\n"
        "  }, i);\n"
        "  if (!rect || !rect.w) { detailState = 'card_invisible'; break; }\n"
        "  // 必须真实鼠标点击：xsec_token 是前端点击后拼到 URL 上的，直接 goto /explore 会 404\n"
        "  await page.mouse.click(rect.x, rect.y);\n"
        "  await new Promise((r) => setTimeout(r, 2800));\n"
        "  let detail = await page.evaluate(() => {\n"
        "    const box = document.querySelector('.note-content') || document.querySelector('#detail-title') || null;\n"
        "    const text = box ? (box.innerText || '').replace(/\\s+/g, ' ').trim().slice(0, 4000) : '';\n"
        "    let images = [];\n"
        "    try {\n"
        "      const st = window.__INITIAL_STATE__ || {};\n"
        "      const map = (st.note && st.note.noteDetailMap) || {};\n"
        "      const id = (location.pathname.match(/\\/explore\\/([0-9a-z]+)/) || [])[1] || '';\n"
        "      // map 里还有 undefined/'' 这类占位键，必须按当前笔记 id 取，不能拿第一个\n"
        "      const entry = (map[id] && map[id].note) || Object.values(map).map((v) => v && v.note).find((n) => n && n.imageList && n.imageList.length) || null;\n"
        "      images = entry ? entry.imageList.map((x) => x.urlDefault || x.url || '').filter(Boolean) : [];\n"
        "    } catch (e) { images = []; }\n"
        "    return { url: location.href, text, images: images.slice(0, 9), note: location.pathname.startsWith('/explore/'), token: /xsec_token=/.test(location.search) };\n"
        "  });\n"
        "  if (detail.note && detail.token && !detail.images.length) {\n"
        "    // 图集是异步补进来的：多等一轮再读一次，别把「还没加载」当成「没有图」\n"
        "    await new Promise((r) => setTimeout(r, 1800));\n"
        "    const again = await page.evaluate(() => {\n"
        "      let images = [];\n"
        "      try {\n"
        "        const st = window.__INITIAL_STATE__ || {};\n"
        "        const map = (st.note && st.note.noteDetailMap) || {};\n"
        "        const id = (location.pathname.match(/\\/explore\\/([0-9a-z]+)/) || [])[1] || '';\n"
        "        const entry = (map[id] && map[id].note) || Object.values(map).map((v) => v && v.note).find((n) => n && n.imageList && n.imageList.length) || null;\n"
        "        images = entry ? entry.imageList.map((x) => x.urlDefault || x.url || '').filter(Boolean) : [];\n"
        "      } catch (e) { images = []; }\n"
        "      return images.slice(0, 9);\n"
        "    });\n"
        "    if (again.length) detail.images = again;\n"
        "  }\n"
        "  if (detail.note && detail.token && detail.text) {\n"
        "    detailState = 'ok';\n"
        "    notes.push({ url: detail.url, text: detail.text, images: detail.images });\n"
        "    break;\n"
        "  }\n"
        "  notes.push({ url: card.href, text: card.text, images: card.cover ? [card.cover] : [], detail: 'open_failed' });\n"
        "  detailState = detail.note ? 'no_token' : 'open_failed';\n"
        "  break;\n"
        "}\n"
        "if (!notes.length) {\n"
        "  for (const card of cards) notes.push({ url: card.href, text: card.text, images: card.cover ? [card.cover] : [], detail: 'card_only' });\n"
        "}\n"
        f"await fs.writeFile(OUT, JSON.stringify({{title: probe.title, head: probe.head, loginWall: probe.loginWall, cards: cards.length, notes, detailState}}, null, 1), 'utf8');\n"
        "console.log(JSON.stringify({ ok: true, cards: cards.length, notes: notes.length }));\n"
    )


def search_xhs(keyword: str, workdir: Path, timeout: int = 180) -> tuple[bool, list[dict], str]:
    """小红书搜一个关键词，返回 (ok, notes, error)；笔记配图顺带 OCR。"""
    if not available() or not keyword:
        return False, [], "unavailable"
    workdir.mkdir(parents=True, exist_ok=True)
    out_path = workdir / f"xhs_search_{abs(hash(keyword)) % 10**8}.json"
    try:
        browser._run_wrapper(_xhs_search_script(keyword, out_path, XHS_DETAILS), workdir, timeout)
    except browser.BrowserError as error:
        return False, [], str(error)
    if not out_path.exists():
        return False, [], "no_output_file"
    try:
        data = json.loads(out_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return False, [], "bad_output"
    head = str(data.get("title") or "")
    notes = [n for n in (data.get("notes") or []) if isinstance(n, dict)]
    if data.get("loginWall"):
        # 登录墙不是风控：不要把 weibo 一起拖进冷却，但这条通道本轮确实没结果
        return False, [], "login_wall"
    if not notes:
        # 页面没给卡片不一定是风控：可能是没登录、加载慢、或这条检索词本来就没结果。
        # 只有命中真正的风控词才算 blocked（会写冷却），其余按普通失败处理。
        hit = blocked(head)
        return False, [], (f"blocked:{hit}" if hit else "no_cards")
    hit = blocked(head)
    if hit:
        return False, [], f"blocked:{hit}"
    ocr_dir = workdir / "xhs-ocr"
    for index, note in enumerate(notes, 1):
        texts = []
        for image_index, image_url in enumerate((note.get("images") or [])[:6], 1):
            text = ocr._ocr_one(
                image_url, ocr_dir, index=index * 10 + image_index, timeout=90,
                referer="https://www.xiaohongshu.com/",
            )
            if text:
                texts.append(text)
        note["ocr"] = "\n".join(texts)
    return True, notes, ""


def collect(pan: dict, workdir: Path) -> dict:
    """一个盘的社媒材料：微博 + 小红书，串行、限速、命中风控即停。"""
    started = time.time()
    materials: list[dict] = []
    errors: list[str] = []
    state = cooldown()
    if state:
        return {"ok": False, "error": f"cooldown_until:{state.get('until')}", "materials": [], "elapsed": 0.0}

    for index, keyword in enumerate(keywords(pan)):
        if index:
            _pause()
        ok, posts, error = search_weibo(keyword, workdir)
        if not ok:
            if str(error).startswith("blocked"):
                set_cooldown(f"weibo:{error}", hours=6)
                return {"ok": False, "error": error, "materials": materials, "elapsed": round(time.time() - started, 1)}
            errors.append(f"weibo:{error}")
        for post in posts:
            materials.append(
                {
                    "platform": "weibo",
                    "url": post.get("url") or "",
                    "title": str(post.get("text") or "")[:80],
                    "text": str(post.get("text") or ""),
                }
            )
        _pause()
        ok, notes, error = search_xhs(keyword, workdir)
        if not ok:
            if str(error).startswith("blocked"):
                # 小红书风控更敏感：一命中就整轮停掉，并冷却
                set_cooldown(f"xhs:{error}", hours=8)
                return {"ok": False, "error": error, "materials": materials, "elapsed": round(time.time() - started, 1)}
            if error == "login_wall":
                # 登录墙：小红书这条本轮用不了，但微博照跑，也不要写冷却
                errors.append("xhs:login_wall")
                continue
            errors.append(f"xhs:{error}")
        for note in notes:
            materials.append(
                {
                    "platform": "xhs",
                    "url": note.get("url") or "",
                    "title": str(note.get("text") or "")[:80],
                    "text": str(note.get("text") or ""),
                    "ocr": str(note.get("ocr") or ""),
                }
            )

    return {
        "ok": True,
        "error": ";".join(errors)[:300],
        "materials": materials,
        "elapsed": round(time.time() - started, 1),
    }


def social_pan(pan: dict, workdir: Path, timeout: int = 150) -> dict:
    """一个盘的社媒通道：找材料 → 走同一套抽取（schema 与 workbuddy / DeepSeek 一致）。"""
    from .backfill_ds import _extract

    started = time.time()
    gathered = collect(pan, workdir)
    materials = gathered.get("materials") or []
    if not materials:
        return {
            "ok": False,
            "error": gathered.get("error") or "no_results",
            "items": [],
            "elapsed": round(time.time() - started, 1),
            "sources": 0,
        }

    lines = []
    for material in materials[:12]:
        lines.append(
            f"[{material['platform']}] {material['url']}\n"
            f"正文：{material['text'][:1200]}\n"
            + (f"配图OCR：{material['ocr'][:1200]}\n" if material.get("ocr") else "")
        )
    prompt = (
        f"目标盘：{pan.get('pan')}\n别名：{pan.get('alias') or '无'}\n"
        f"表里缺：{', '.join(pan.get('gaps') or [])}\n\n"
        f"社媒材料（微博 / 小红书，含配图 OCR）：\n{chr(10).join(lines)}\n\n"
        "只根据上面的材料抽取这一个盘；材料里没有它就排除。"
        "quote 必须能在该条材料正文或配图 OCR 里找到；找不到数字就写 null。"
    )
    extracted = _extract(prompt, timeout=timeout)
    items = []
    for row in extracted.get("items") or []:
        if isinstance(row, dict):
            row["lane"] = "social"
            items.append(row)
    return {
        "ok": bool(extracted.get("ok")),
        "error": extracted.get("error") or gathered.get("error") or "",
        "items": items,
        "elapsed": round(time.time() - started, 1),
        "sources": len(materials),
    }
